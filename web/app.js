/* question appears transcribed as a short line anchored to the avatar */
/* panel. The copilot WRITES on a card next to the board: its real     */
/* engine tool calls show as chips, then the answer's phrases (the     */
/* script's [acortada] summaries of the real answer) appear at reading */
/* rhythm. The engine only shows numbers (layers 1–3, untouched).      */
/*                                                                    */
/* Texts come from web/exchanges.json — the copilot's real answers     */
/* from one live Baseten run (provenance: web/EXCHANGES.md). Nothing   */
/* is typed, generated or recomputed here. At most two exchanges,      */
/* tied to Play the lead on the video path: minute 0 (before the       */
/* pre-shift call) and minute 165 (detection, before the mid-shift      */
/* call). Order is question -> card -> YOUR CALL. When the card is     */
/* done it folds itself into the night log; the night never waits on   */
/* a click on the card.                                                */
/*                                                                    */
/* The avatar is a geometric bust in two neutral board tones — no      */
/* semantic color, no mouth, no lip-sync. Since Alberto's repertoire    */
/* call (2026-11-02 19:31) it also LIVES, soberly: its two dot eyes     */
/* shift as one group (setGaze: card / call / hero / down), it listens  */
/* while the engine chips arrive (gaze down, head inclined, one slow    */
/* double blink). Since D3 (Mesa PR #204) the frame's speech ring is    */
/* the PERSON'S alone: it beats while the lead speaks (question, and    */
/* the nod that answers a call) — while the copilot writes, the card    */
/* carries its own writing caret and the avatar only watches/listens.  */
/* clear nod. Around the step (minute                                  */
/* 150) the panel RETREATS: the fold starts 0.5 s of playback before   */
/* minute 150 (at the current speed) and the panel returns at minute   */
/* 158, clear of the hero beat and back before the detection. Plan B   */
/* (body.no-avatar) removes the panel entirely; the question line      */
/* then sits with the card and everything else works the same.         */
