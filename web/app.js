/* PR #205: focus by beat, recording mode only. Whatever does not take
   part in the current moment drops to 40% opacity (CSS): during an
   exchange the focus is card + avatar + hero; while a YOUR CALL is
   open, the bar; during the step window (the avatar's retreat window,
   minutes ~145–158), the hero number alone; the running night is all
   at 100%. The beats reuse the states the page already knows —
   exRunning, pending, and the retreat window — no new timings. */
function updateFocus() {
  const b = document.body;
  let f = null;
  if (b.classList.contains("recording")) {
    const retreatStart = 150 - 0.5 * speed;
    if (pos >= retreatStart && pos < 158) f = "step";
    else if (pending) f = "call";
    else if (exRunning) f = "exchange";
  }
  b.classList.toggle("focus-step", f === "step");
  b.classList.toggle("focus-call", f === "call");
  b.classList.toggle("focus-exchange", f === "exchange");
}

function render() {
  const m = Math.min(T.meta.shiftMinutes, Math.floor(pos));
  const ots = S.projectedOts[m];
  $("clock").textContent = clockOf(m);
  let minuteText = `Minute ${m} of ${T.meta.shiftMinutes}`;
  const active = T.stoppages.find((s) => m >= s.start && m < s.end);
  if (active) minuteText += ` · line stopped since ${active.startClock}`;
  $("minuteLabel").textContent = minuteText;
  $("otsValue").textContent = fmt(ots);
  const pill = $("statusPill");
  if (m >= T.meta.shiftMinutes) {
    pill.textContent = `NIGHT CLOSED — ${fmt(S.outcome.nightOts)}%`;
    pill.className = "status-pill done";
  } else if (ots >= T.meta.otsTarget) {
    pill.textContent = "ON TRACK";
    pill.className = "status-pill ok";
  } else {
    pill.textContent = "AT RISK";
    pill.className = "status-pill risk";
  }
  $("scrubber").value = m;
  // PR #205: in recording mode the hero number itself carries the
  // state color — engine semantics, the same three bands as the gate
  // seals (green >= target, amber below target, red below 90: the
  // confirmed-damage threshold the seals already use). In dev mode the
  // classes stay off and the number keeps its plain color.
  const otsEl = $("otsValue");
  const onRecord = document.body.classList.contains("recording");
  otsEl.classList.toggle("ots-ok", onRecord && ots >= T.meta.otsTarget);
  otsEl.classList.toggle("ots-warn", onRecord && ots < T.meta.otsTarget && ots >= 90);
  otsEl.classList.toggle("ots-bad", onRecord && ots < 90);
  updateFocus();
  drawCurve(m);
  updateGates(m);
  if (chainReady) {
    updateChain(m);
    drawChain();
  }
  // D1: the decision record shows only blocks that have already
  // happened — the mid-shift block does not exist on the board until
  // its minute arrives (no dormant preview of a future detection).
  const midReached = m >= T.panel.midshift.minute;
  $("midshiftBlock").hidden = !midReached;
  $("midshiftBlock").classList.toggle("active", midReached);
  $("midshiftBlock").classList.toggle("dormant", !midReached);
  // D1: scrubber ticks for future events stay hidden until reached.
  document.querySelectorAll(".scrubber-markers .tick").forEach((tk) => {
    tk.classList.toggle("future", Number(tk.dataset.minute) > m);
  });
  const ended = m >= T.meta.shiftMinutes;
  $("outcomeBlock").hidden = !ended;
  if (ended && mode === "play") fillPlayOutcome();
  if (mode === "play") updateExchangeLayer(ended);
  updateBadge();
}

function tick(ts) {
  if (lastTs === null) lastTs = ts;
  const dt = (ts - lastTs) / 1000;
  lastTs = ts;
  if (playing) {
    pos += speed * dt;
    // Play the lead: the mid-shift stop fires exactly at the decision
    // minute, however coarse the frame step is.
    if (mode === "play" && midArmed && pos >= MID_MINUTE) {
      pos = MID_MINUTE;
      render();
      arriveMidShift();
    } else if (pos >= T.meta.shiftMinutes) {
      pos = T.meta.shiftMinutes;
      setPlaying(false);
      render();
    } else {
      render();
    }
  }
  requestAnimationFrame(tick);
}

