function exById(id) {
  return EX ? EX.exchanges.find((e) => e.id === id) : null;
}

/* The repertoire's gaze states (Alberto, 2026-11-02 19:31): the two
   dot eyes move as one group — "card" while the copilot writes,
   "call" while a YOUR CALL bar is open, "hero" for one beat when the
   mid-shift alert lands (the OTS number, up top), "down" while
   listening to the engine chips. null = resting center. The CSS in
   style.css (layer 4) owns the actual offsets. */
const GAZE_CLASSES = ["gaze-card", "gaze-call", "gaze-hero", "gaze-down"];
function setGaze(state) {
  const panel = $("avatarPanel");
  if (!panel) return;
  panel.classList.remove(...GAZE_CLASSES);
  if (state) panel.classList.add("gaze-" + state);
}

function exLater(fn, ms) {
  const g = exGen;
  const id = setTimeout(() => { if (g === exGen) fn(); }, ms);
  exTimers.push(id);
}

function cancelExchanges() {
  exGen++;
  exTimers.forEach(clearTimeout);
  exTimers = [];
  exRunning = false;
  const panel = $("avatarPanel");
  if (panel) panel.classList.remove("ring-on", "asking", "listening", ...GAZE_CLASSES);
  if (cardCaret) { cardCaret.remove(); cardCaret = null; }
}

function resetExchangeLayer() {
  exDone = { start: false, detection: false };
  logHighlighted = false;
  proofShown = false;
  const panel = $("avatarPanel");
  if (panel) panel.classList.remove("listening", "ring-on", ...GAZE_CLASSES);
  if (cardCaret) { cardCaret.remove(); cardCaret = null; }
  $("nightLogList").innerHTML = "";
  $("nightLog").hidden = true;
  $("nightLog").classList.remove("highlight");
  $("exchangeCard").hidden = true;
  $("exchangeQuestion").hidden = true;
}

function phraseDelay(text) {
  // Reading rhythm: roughly 30 characters per second, with a floor so
  // short phrases still land and a cap so long ones do not stall.
  return Math.min(2600, Math.max(750, 420 + text.length * 34));
}

function startExchange(id, after) {
  const ex = exById(id);
  if (!ex || exDone[id]) { after(); return; }
  if (exRunning) return;
  exRunning = true;
  exMinute = ex.minute;
  setPlaying(false);
  render();   // refresh the header path badge for the paused exchange
  const panel = $("avatarPanel");

  // 1) The lead speaks: the question appears, transcribed, and the
  //    character tilts briefly toward the board.
  const q = $("exchangeQuestion");
  q.innerHTML = "";
  const lab = document.createElement("span");
  lab.className = "q-label";
  lab.textContent = "THE LEAD — SPOKEN, TRANSCRIBED";
  q.appendChild(lab);
  q.appendChild(document.createTextNode("“" + ex.question + "”"));
  q.hidden = false;
  panel.classList.add("asking");
  // D3: the speech ring belongs to the PERSON alone — it beats while
  // the lead speaks (his question on screen), never while the copilot
  // writes. It goes off the moment the card opens.
  panel.classList.add("ring-on");
  setGaze(null);   // while he speaks, the gaze rests at center
  exLater(() => panel.classList.remove("asking"), 1100);

  // 2) The copilot writes: chips of its real tool calls first, then the
  //    phrases at reading rhythm. While the CHIPS arrive the character
  //    listens: gaze down, head inclined toward the card, one slow
  //    double blink (CSS). When the PHRASES start, the gaze goes to
  //    the card — no ring: the ring is the person's (D3). For
  //    the mid-shift alert the gaze first flicks up to the hero number
  //    for one beat, then settles on the card.
  exLater(() => {
    const card = $("exchangeCard");
    $("exchangeClock").textContent = `${ex.clock} · minute ${ex.minute}`;
    const chipsEl = $("exchangeChips");
    chipsEl.innerHTML = ex.calls.map((c) =>
      `<span class="xchip"><span class="xchip-tool">engine · ${c.tool}</span>` +
      ` &rarr; ${c.headline}</span>`).join("");
    $("exchangePhrases").innerHTML = "";
    card.hidden = false;
    panel.classList.remove("asking");
    panel.classList.remove("ring-on");   // the lead has spoken; the card writes now
    // D3: while the copilot writes, the CARD carries its own writing
    // caret at the end of the text — the avatar only watches/listens.
    cardCaret = document.createElement("span");
    cardCaret.className = "xcaret";
    cardCaret.id = "exchangeCaret";
    $("exchangePhrases").appendChild(cardCaret);
    panel.classList.add("listening");
    setGaze("down");
    const chips = chipsEl.querySelectorAll(".xchip");
    chips.forEach((ch, i) => exLater(() => ch.classList.add("in"), 200 + i * 280));
    let t = 200 + chips.length * 280 + 400;
    exLater(() => {
      panel.classList.remove("listening");
      if (ex.id === "detection") {
        setGaze("hero");
        exLater(() => setGaze("card"), 650);
      } else {
        setGaze("card");
      }
    }, t);
    ex.phrases.forEach((ph) => {
      exLater(() => {
        const p = document.createElement("p");
        p.className = "phrase";
        p.textContent = ph;
        // Phrases land before the caret: the caret always trails the
        // text being written (D3).
        $("exchangePhrases").insertBefore(p, cardCaret);
        requestAnimationFrame(() => p.classList.add("in"));
      }, t);
      t += phraseDelay(ph);
    });
    // 3) The card folds itself into the night log; the call follows.
    exLater(() => finishExchange(ex, after), t + 950);
  }, 1000);
}

function finishExchange(ex, after) {
  const card = $("exchangeCard");
  card.classList.add("folding");
  if (cardCaret) { cardCaret.remove(); cardCaret = null; }
  exLater(() => {
    card.hidden = true;
    card.classList.remove("folding");
    $("avatarPanel").classList.remove("ring-on", "listening");
    $("exchangeQuestion").hidden = true;
    addLogEntry(ex);
    exDone[ex.id] = true;
    exRunning = false;
    after();
  }, 480);
}

/* The engine's answers carry markdown bold (`**…**`) from the model
   run. PR #205: no raw markdown marks on any recording surface — the
   log shows the answer as plain text. (The card's phrases never had
   marks; this is only about the verbatim.) */
const plainText = (s) => s.replace(/\*/g, "");

function addLogEntry(ex) {
  $("nightLog").hidden = false;
  const li = document.createElement("li");
  li.className = "log-entry";
  const clock = document.createElement("span");
  clock.className = "log-clock";
  clock.textContent = ex.clock;
  const q = document.createElement("span");
  q.className = "log-q";
  q.textContent = "“" + ex.question + "”";
  const text = document.createElement("span");
  text.className = "log-text";
  text.textContent = ex.logText;
  li.append(clock, q, text);
  if (document.body.classList.contains("recording") && ex.answer) {
    // D2 + PR #205: in recording mode the decision-record panel is
    // folded away, so the engine's literal output — the evidence —
    // lives here in the night log. But the entry rests FOLDED to its
    // one-line summary above (clock + question + result); the full
    // literal rides along hidden and is deployed only at the close
    // of the night, for ~1 s, as proof (updateExchangeLayer).
    const ans = document.createElement("span");
    ans.className = "log-proof";
    ans.hidden = true;
    ans.textContent = plainText(ex.answer);
    li.appendChild(ans);
  }
  $("nightLogList").appendChild(li);
}

function arriveMidShift() {
  // Detection minute reached on the video path: exchange 2 first
  // (question -> card), then the mid-shift call. If the exchange is
  // already in the log, the call opens directly.
  startExchange("detection", () => openDecision("mid"));
}

function updateExchangeLayer(ended) {
  // The panel retreats for the hero beat: the fold starts 0.5 s of
  // playback before minute 150 at the current speed; it returns at
  // minute 158, before the detection at 165 needs it back.
  const retreatStart = 150 - 0.5 * speed;
  $("avatarPanel").classList.toggle("retreated", pos >= retreatStart && pos < 158);
  // At the close of the night the log is highlighted once (~1 s) and
  // stays visible, legible next to the final summary.
  if (ended && !logHighlighted && $("nightLogList").children.length) {
    logHighlighted = true;
    $("nightLog").classList.add("highlight");
    setTimeout(() => $("nightLog").classList.remove("highlight"), 1200);
  }
  // PR #205: at that same close, and only then, the log deploys the
  // engine's full literal output for ~1 s — the proof — then folds
  // back to the one-line summaries.
  if (ended && !proofShown && document.body.classList.contains("recording")) {
    const proofs = document.querySelectorAll(".log-proof");
    if (proofs.length) {
      proofShown = true;
      proofs.forEach((el) => { el.hidden = false; });
      setTimeout(() => proofs.forEach((el) => { el.hidden = true; }), 1000);
    }
  }
}

