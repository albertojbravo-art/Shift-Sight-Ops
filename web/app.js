const Y_MIN = 60, Y_MAX = 100;

function drawCurve(m) {
  const canvas = $("curve");
  const dpr = window.devicePixelRatio || 1;
  const w = canvas.clientWidth, h = canvas.clientHeight;
  if (canvas.width !== Math.round(w * dpr) || canvas.height !== Math.round(h * dpr)) {
    canvas.width = Math.round(w * dpr);
    canvas.height = Math.round(h * dpr);
  }
  const ctx = canvas.getContext("2d");
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, w, h);

  const padL = 36, padR = 12, padT = 20, padB = 24;
  const iw = w - padL - padR, ih = h - padT - padB;
  const X = (minute) => padL + (minute / T.meta.shiftMinutes) * iw;
  const Y = (v) => padT + (1 - (v - Y_MIN) / (Y_MAX - Y_MIN)) * ih;

  ctx.font = "bold 11px system-ui, sans-serif";

  // Stoppage spans — drawn ONLY once the stoppage has started, and
  // only up to the current minute while it runs (D1, Mesa PR #204:
  // the board never shows the future). Once it ends, the span stays
  // as history, closed at its end minute. The label names the start
  // only — no end clock is ever printed.
  for (const s of T.stoppages) {
    if (m < s.start) continue;
    const x2 = X(Math.min(s.end, m));
    ctx.fillStyle = "rgba(248,113,113,0.14)";
    ctx.fillRect(X(s.start), padT, x2 - X(s.start), ih);
    ctx.fillStyle = "#f87171";
    ctx.fillRect(X(s.start), padT, x2 - X(s.start), 2);
    ctx.fillStyle = "rgba(248,113,113,0.85)";
    ctx.fillText(`STOPPAGE — line stopped since ${s.startClock}`, X(s.start) + 3, padT - 6);
  }

  // Gridlines + y labels.
  for (const v of [60, 70, 80, 90]) {
    ctx.strokeStyle = "rgba(147,165,187,0.15)";
    ctx.beginPath(); ctx.moveTo(padL, Y(v)); ctx.lineTo(w - padR, Y(v)); ctx.stroke();
    ctx.fillStyle = "#93a5bb";
    ctx.fillText(String(v), 10, Y(v) + 3);
  }
  // Target line at 99.
  ctx.strokeStyle = "#34d399";
  ctx.setLineDash([6, 4]);
  ctx.beginPath(); ctx.moveTo(padL, Y(T.meta.otsTarget)); ctx.lineTo(w - padR, Y(T.meta.otsTarget)); ctx.stroke();
  ctx.setLineDash([]);
  ctx.fillStyle = "#34d399";
  ctx.fillText("99% TARGET", w - padR - 62, Y(T.meta.otsTarget) - 5);

  // X labels (shift clock).
  ctx.fillStyle = "#93a5bb";
  for (const minute of [0, 120, 240, 360, 480, 600]) {
    ctx.fillText(clockOf(minute), X(minute) - 12, h - 8);
  }

  // The series, drawn as steps — ELAPSED ONLY. The future is not drawn:
  // ahead of the playhead, only the 99% target line marks the axis, and
  // stoppage spans appear only once their stoppage has started (D1).
  // The one static reference allowed is the
  // active branch's own initial projection (a constant of the trace,
  // series[0]), as a dashed gray line.
  const series = S.projectedOts;
  const target = T.meta.otsTarget;
  ctx.strokeStyle = "rgba(147,165,187,0.55)";
  ctx.setLineDash([5, 5]);
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(padL, Y(series[0]));
  ctx.lineTo(w - padR, Y(series[0]));
  ctx.stroke();
  ctx.setLineDash([]);
  const drawRange = (from, to) => {
    for (let i = Math.max(1, from); i <= to; i++) {
      const vPrev = series[i - 1], v = series[i];
      const below = v < target || vPrev < target;
      ctx.strokeStyle = below ? "#f87171" : "#2dd4bf";
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.moveTo(X(i - 1), Y(vPrev));
      ctx.lineTo(X(i), Y(vPrev));
      ctx.lineTo(X(i), Y(v));
      ctx.stroke();
    }
  };
  drawRange(1, Math.floor(m));
  ctx.lineWidth = 1;

  // Decision markers on the axis — only for minutes already reached
  // (D1: no marks of future events on the time bar).
  for (const mk of T.markers) {
    if (mk.minute > m) continue;
    ctx.fillStyle = "#fbbf24";
    const x = X(mk.minute);
    ctx.beginPath();
    ctx.moveTo(x, h - padB + 2); ctx.lineTo(x - 4, h - padB + 9); ctx.lineTo(x + 4, h - padB + 9);
    ctx.closePath(); ctx.fill();
  }

  // Playhead.
  if (m > 0) {
    ctx.strokeStyle = "rgba(219,228,238,0.5)";
    ctx.beginPath(); ctx.moveTo(X(m), padT); ctx.lineTo(X(m), padT + ih); ctx.stroke();
    ctx.fillStyle = "#fff";
    ctx.beginPath(); ctx.arc(X(m), Y(series[Math.floor(m)]), 3.5, 0, Math.PI * 2); ctx.fill();
  }
}

