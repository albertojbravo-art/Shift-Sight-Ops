/* ------------------------------------------------------------------ */
/* Layer 2 — live chain (mass flow).                                  */
/*                                                                    */
/* The engine is a FLUID model: there are no individual items, so     */
/* nothing here is a decorative particle with an invented rhythm.     */
/* Every visual element is a monotone rendering of ONE series in the  */
/* ACTIVE source's areas (root traces in Replay — the no-intervention  */
/* night; the chosen branch in Play the lead):                         */
/*                                                                    */
/*   node staff number       <- areas.staffPresent[area][m]           */
/*   node processed number   <- areas.processedCumulative[area][m]    */
/*   node queue bar + count  <- areas.queue[area][m]; bar width is    */
/*      queue / QUEUE_MAX, one scale shared by all five areas, where  */
/*      QUEUE_MAX is the largest queue in the replay (Induct's peak), */
/*      computed from the trace at load and declared in the panel.    */
/*   link flow (dash speed + opacity) <- areas.processedPerMinute     */
/*      [origin][m], normalized by PPM_REF (the largest source rate  */
/*      in the trace, declared in the panel). The dash PHASE is the   */
/*      time-integral of that same series: phase(m) = sum over the    */
/*      minutes before m of processedPerMinute[origin] (exactly the   */
/*      mass the origin has processed), with blocked minutes          */
/*      contributing 0. The phase is therefore a pure function of     */
/*      the playhead position — seeking needs no history.             */
/*   link stopped (red band, no flow) <- areas.linksBlocked           */
/*      ["Origin->Dest"][m].                                          */
/*   held-mass pool (amber bulge at the destination end of a link,    */
/*      height ∝ held mass)  <- areas.packedUndispatched[m] for the   */
/*      Pack->Shipping link (the "dam": peaks at 8,167.5 at minute    */
/*      465 and is 0 again at 466); for the other links it is         */
/*      areas.staged[origin][m], the origin's output buffer held by   */
/*      a stopped link (only Picking is ever non-zero: it peaks at    */
/*      7,030 during the Picking->Induct stoppage). Both pool series  */
/*      share one scale, HELD_MAX (the larger peak), declared in the  */
/*      panel.                                                        */
/*   link status chips       <- the same series, read as text.        */
/*                                                                    */
/* Masses are rounded to whole items for display only; bars, pools    */
/* and phases use the exact trace values.                             */
/* ------------------------------------------------------------------ */
let chainReady = false;
let CHAIN_AREAS = [];
let CHAIN_LINKS = [];
let QUEUE_MAX = 1;
let HELD_MAX = 1;
let PPM_REF = 1;
const ITEMS_PER_CYCLE = 600; // one full dash cycle per 600 items processed at the source

const fmtInt = (x) => Math.round(x).toLocaleString("en-US");

function heldMass(L, m) {
  if (L.key === "Pack->Shipping") return S.areas.packedUndispatched[m];
  return S.areas.staged[L.from][m];
}

/* Node/link DOM is built once; the scales and the flow-phase integrals are
   recomputed from the ACTIVE source on every source switch, so Replay
   (source = root traces) renders with exactly the layer-2 scales. */
function buildChain() {
  CHAIN_AREAS = T.areas.order.slice();
  $("chainNodes").innerHTML = CHAIN_AREAS.map((a) => `
    <div class="chain-node" id="node-${a}">
      <div class="node-name">${a}</div>
      <div class="node-meta">staff <b id="node-staff-${a}">&mdash;</b></div>
      <div class="node-cum"><b id="node-cum-${a}">0</b> processed</div>
      <div class="node-meta">queue <b id="node-queue-${a}">0</b> items</div>
      <div class="node-queue-bar"><div id="node-queuebar-${a}"></div></div>
    </div>`).join("");
  $("chainLinks").innerHTML = CHAIN_AREAS.slice(0, -1).map((L, i) =>
    `<span class="link-chip" id="link-chip-${i}"></span>`).join("");
  buildChainScales(S);
  chainReady = true;
}

function buildChainScales(src) {
  const A = src.areas;
  QUEUE_MAX = Math.max(...CHAIN_AREAS.map((a) => Math.max(...A.queue[a])));
  HELD_MAX = Math.max(
    Math.max(...A.packedUndispatched),
    ...CHAIN_AREAS.map((a) => Math.max(...A.staged[a]))
  );
  // Link origins are every area except the last (Shipping ships out).
  PPM_REF = Math.max(
    ...CHAIN_AREAS.slice(0, -1).map((a) => Math.max(...A.processedPerMinute[a]))
  );
  CHAIN_LINKS = CHAIN_AREAS.slice(0, -1).map((from, i) => {
    const to = CHAIN_AREAS[i + 1];
    const key = `${from}->${to}`;
    const blockedArr = A.linksBlocked[key];
    const ppmArr = A.processedPerMinute[from];
    // effCum[k] = items the origin processed in minutes < k while the link
    // was open — the flow-phase integral, frozen across blocked minutes.
    const effCum = [0];
    for (let t = 0; t <= T.meta.shiftMinutes; t++) {
      effCum.push(effCum[t] + (blockedArr[t] ? 0 : ppmArr[t]));
    }
    return { from, to, key, effCum };
  });
  $("chainNote").textContent =
    `Flow strength follows items processed per minute at each source area ` +
    `(full strength = ${fmtInt(PPM_REF)} items/min) · queue bars share one scale ` +
    `(peak ${fmtInt(QUEUE_MAX)} items) · amber pool = mass held at a stopped link ` +
    `(shared scale, peak ${fmtInt(HELD_MAX)} items)`;
}

function updateChain(m) {
  const A = S.areas;
  for (const a of CHAIN_AREAS) {
    $("node-staff-" + a).textContent = A.staffPresent[a][m];
    $("node-cum-" + a).textContent = fmtInt(A.processedCumulative[a][m]);
    $("node-queue-" + a).textContent = fmtInt(A.queue[a][m]);
    $("node-queuebar-" + a).style.width = (A.queue[a][m] / QUEUE_MAX) * 100 + "%";
  }
  CHAIN_LINKS.forEach((L, i) => {
    const chip = $("link-chip-" + i);
    const held = heldMass(L, m);
    const heldTxt = held > 0.5 ? ` · held ${fmtInt(held)}` : "";
    if (A.linksBlocked[L.key][m]) {
      chip.className = "link-chip blocked";
      chip.innerHTML = `<b>${L.from} &rarr; ${L.to}</b> · STOPPED${heldTxt}`;
    } else {
      chip.className = "link-chip";
      chip.innerHTML =
        `<b>${L.from} &rarr; ${L.to}</b> · ${fmt(A.processedPerMinute[L.from][m])}/min${heldTxt}`;
    }
  });
}

/* Flow phase, in items processed at the origin while the link was open.
   Pure function of the playhead position p (float minutes). */
function flowPhase(L, p) {
  const m = Math.min(T.meta.shiftMinutes, Math.floor(p));
  let v = L.effCum[m];
  if (!S.areas.linksBlocked[L.key][m]) {
    v += S.areas.processedPerMinute[L.from][m] * (p - m);
  }
  return v;
}

function pathRoundRect(ctx, x, y, w, h, r) {
  const rr = Math.min(r, w / 2, h / 2);
  ctx.beginPath();
  ctx.moveTo(x + rr, y);
  ctx.lineTo(x + w - rr, y);
  ctx.arcTo(x + w, y, x + w, y + rr, rr);
  ctx.lineTo(x + w, y + h - rr);
  ctx.arcTo(x + w, y + h, x + w - rr, y + h, rr);
  ctx.lineTo(x + rr, y + h);
  ctx.arcTo(x, y + h, x, y + h - rr, rr);
  ctx.lineTo(x, y + rr);
  ctx.arcTo(x, y, x + rr, y, rr);
  ctx.closePath();
}

function drawLink(ctx, L, g, m) {
  const A = S.areas;
  const width = g.x2 - g.x1;
  if (width < 10) return;
  const blocked = A.linksBlocked[L.key][m];
  const ppm = A.processedPerMinute[L.from][m];
  const inten = blocked ? 0 : Math.min(1, ppm / PPM_REF);
  const held = heldMass(L, m);
  const bandH = 18;

  // Track. A blocked link is a SOLID red band (not a translucent fill).
  ctx.fillStyle = blocked ? "#f87171" : "#1b2635";
  pathRoundRect(ctx, g.x1, g.y - bandH / 2, width, bandH, 9);
  ctx.fill();

  if (blocked) {
    ctx.fillStyle = "#fff";
    ctx.font = "bold 13px system-ui, sans-serif";
    ctx.textAlign = "center";
    ctx.fillText("✕", (g.x1 + g.x2) / 2, g.y + 5);
    ctx.textAlign = "left";
  } else if (inten > 0) {
    // Moving dashes; phase from the processed-mass integral (see header).
    const spacing = 30;
    const phasePx = (flowPhase(L, pos) / ITEMS_PER_CYCLE) * spacing;
    const len = 7 + 11 * inten;
    ctx.save();
    ctx.beginPath();
    ctx.rect(g.x1, g.y - bandH / 2, width, bandH);
    ctx.clip();
    ctx.strokeStyle = `rgba(45,212,191,${0.2 + 0.75 * inten})`;
    ctx.lineWidth = 7;
    ctx.lineCap = "round";
    ctx.beginPath();
    const off = ((phasePx % spacing) + spacing) % spacing;
    for (let x = g.x1 - spacing + off; x < g.x2; x += spacing) {
      ctx.moveTo(x, g.y);
      ctx.lineTo(x + len, g.y);
    }
    ctx.stroke();
    ctx.restore();
    ctx.lineWidth = 1;
  }

  // Held-mass pool at the destination end of the link.
  if (held > 0.5) {
    const poolW = Math.min(64, width * 0.8);
    const poolH = bandH + 38 * (held / HELD_MAX);
    const px = g.x2 - poolW;
    ctx.fillStyle = "rgba(251,191,36,0.85)";
    pathRoundRect(ctx, px, g.y - poolH / 2, poolW, poolH, 6);
    ctx.fill();
    ctx.fillStyle = "#fbbf24";
    ctx.font = "bold 11px system-ui, sans-serif";
    ctx.textAlign = "center";
    ctx.fillText(fmtInt(held), px + poolW / 2, g.y - poolH / 2 - 5);
    ctx.textAlign = "left";
  }
}

function drawChain() {
  const canvas = $("chainCanvas");
  if (!canvas || !chainReady) return;
  const dpr = window.devicePixelRatio || 1;
  const w = canvas.clientWidth, h = canvas.clientHeight;
  if (!w || !h) return;
  if (canvas.width !== Math.round(w * dpr) || canvas.height !== Math.round(h * dpr)) {
    canvas.width = Math.round(w * dpr);
    canvas.height = Math.round(h * dpr);
  }
  const ctx = canvas.getContext("2d");
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, w, h);
  const m = Math.min(T.meta.shiftMinutes, Math.floor(pos));
  const chainRect = $("chain").getBoundingClientRect();
  for (const L of CHAIN_LINKS) {
    const a = $("node-" + L.from).getBoundingClientRect();
    const b = $("node-" + L.to).getBoundingClientRect();
    drawLink(ctx, L, {
      x1: a.right - chainRect.left,
      x2: b.left - chainRect.left,
      y: a.top - chainRect.top + a.height / 2,
    }, m);
  }
}

