function clockOf(minute) {
  const total = 17 * 60 + 30 + Math.floor(minute);
  const hh = String(Math.floor(total / 60) % 24).padStart(2, "0");
  const mm = String(total % 60).padStart(2, "0");
  return `${hh}:${mm}`;
}
const fmt = (x) => x.toFixed(1);

